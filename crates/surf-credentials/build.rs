//! Embeds the read-only R2 credentials into the binary at compile time.
//!
//! Values come from the environment, or from a git-ignored `.env` at the
//! workspace root. Each value is XOR-ed with a key generated fresh for every
//! build, so the secrets never appear as plain text in the binary (this is
//! obfuscation, not encryption: use a read-only, bucket-scoped token).

use std::collections::hash_map::RandomState;
use std::env;
use std::fmt::Write as _;
use std::hash::{BuildHasher, Hasher};
use std::path::PathBuf;

const VARS: [(&str, &str); 5] = [
    ("SURF_R2_ENDPOINT", "ENDPOINT"),
    ("SURF_R2_ACCOUNT_ID", "ACCOUNT_ID"),
    ("SURF_R2_ACCESS_KEY_ID", "ACCESS_KEY_ID"),
    ("SURF_R2_SECRET_ACCESS_KEY", "SECRET_ACCESS_KEY"),
    ("SURF_R2_BUCKET", "BUCKET"),
];

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let dotenv = manifest.join("../../.env");
    println!("cargo:rerun-if-changed={}", dotenv.display());
    for (var, _) in VARS {
        println!("cargo:rerun-if-env-changed={var}");
    }

    let from_file: Vec<(String, String)> = dotenvy::from_path_iter(&dotenv)
        .map(|it| it.filter_map(Result::ok).collect())
        .unwrap_or_default();
    let lookup = |var: &str| -> Option<String> {
        env::var(var)
            .ok()
            .or_else(|| {
                from_file
                    .iter()
                    .find(|(k, _)| k == var)
                    .map(|(_, v)| v.clone())
            })
            .map(|v| v.trim().to_owned())
            .filter(|v| !v.is_empty())
    };

    let mut missing = Vec::new();
    // The endpoint can be given directly, or derived from the account ID.
    let endpoint = lookup("SURF_R2_ENDPOINT")
        .map(|e| e.trim_matches(['"', '\'']).trim_end_matches('/').to_owned())
        .or_else(|| {
            lookup("SURF_R2_ACCOUNT_ID").map(|id| format!("https://{id}.r2.cloudflarestorage.com"))
        });
    let mut values = Vec::new();
    match endpoint {
        Some(e) if e.starts_with("https://") => values.push(("ENDPOINT", e)),
        Some(_) => panic!("\n\nSURF_R2_ENDPOINT must start with https://\n\n"),
        None => missing.push("SURF_R2_ENDPOINT (or SURF_R2_ACCOUNT_ID)"),
    }
    for (var, name) in &VARS[2..] {
        match lookup(var) {
            Some(v) => values.push((name, v.trim_matches(['"', '\'']).to_owned())),
            None if *var == "SURF_R2_BUCKET" => values.push((name, "waves-rips".to_owned())),
            None => missing.push(var),
        }
    }
    if !missing.is_empty() {
        panic!(
            "\n\nsurf needs R2 credentials at build time. Missing: {}\n\
             Copy `.env.example` to `.env` at the repository root and fill it in,\n\
             or export the variables before building.\n\n",
            missing.join(", ")
        );
    }

    let longest = values.iter().map(|(_, v)| v.len()).max().unwrap_or(1);
    let key = random_bytes(longest.max(32));

    let mut out = String::from("// @generated by build.rs — do not edit.\n");
    writeln!(out, "const KEY: [u8; {}] = {:?};", key.len(), key).unwrap();
    for (name, value) in &values {
        let masked: Vec<u8> = value
            .bytes()
            .zip(key.iter().cycle())
            .map(|(b, k)| b ^ k)
            .collect();
        writeln!(out, "const {name}: [u8; {}] = {:?};", masked.len(), masked).unwrap();
    }
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("embedded.rs");
    std::fs::write(dest, out).unwrap();
}

/// Non-cryptographic random bytes from the std hasher's per-process random seed.
fn random_bytes(n: usize) -> Vec<u8> {
    let state = RandomState::new();
    let mut bytes = Vec::with_capacity(n + 8);
    let mut counter = 0u64;
    while bytes.len() < n {
        let mut h = state.build_hasher();
        h.write_u64(counter);
        h.write_u128(
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map(|d| d.as_nanos())
                .unwrap_or_default(),
        );
        bytes.extend_from_slice(&h.finish().to_le_bytes());
        counter += 1;
    }
    bytes.truncate(n);
    bytes
}
