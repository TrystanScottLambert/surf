//! Writes a small demo dataset laid out like the `waves-rips` bucket, for
//! trying the app offline:
//!
//! ```sh
//! cargo run -p surf-query --example demo_data -- /tmp/surf-demo
//! SURF_LOCAL_DIR=/tmp/surf-demo cargo run -p surf-gui
//! ```

use std::path::Path;
use std::sync::Arc;

use datafusion::arrow::array::{
    ArrayRef, BooleanArray, Float64Array, Int64Array, RecordBatch, StringArray,
};
use datafusion::arrow::datatypes::{Field, Schema};
use datafusion::parquet::arrow::ArrowWriter;
use datafusion::parquet::file::metadata::KeyValue;
use datafusion::parquet::file::properties::WriterProperties;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let root = std::env::args()
        .nth(1)
        .ok_or("usage: demo_data <output dir>")?;
    let root = Path::new(&root);

    for (version, n_groups) in [("v1", 2_000i64), ("v2", 5_000)] {
        let dir = root.join("groups").join(version);
        std::fs::create_dir_all(&dir)?;
        std::fs::write(
            dir.join("groups.md"),
            format!(
                "# WAVES group catalogue ({version})\n\n\
                 Friends-of-friends groups identified in the WAVES-Wide fields.\n\n\
                 ## Tables\n\n\
                 | Table | Description |\n|---|---|\n\
                 | `groups.parquet` | One row per group |\n\
                 | `galaxies.parquet` | One row per member galaxy |\n\n\
                 ## Changes\n\n- {version}: demo data generated by `demo_data`.\n"
            ),
        )?;
        write_groups(&dir.join("groups.parquet"), n_groups)?;
        write_galaxies(&dir.join("galaxies.parquet"), n_groups * 8)?;
    }
    let dir = root.join("stars").join("v1");
    std::fs::create_dir_all(&dir)?;
    std::fs::write(
        dir.join("stars.md"),
        "# Stars\n\nA star/galaxy separation catalogue (demo).\n",
    )?;
    write_galaxies(&dir.join("stars.parquet"), 3_000)?;

    println!("Demo data written to {}", root.display());
    Ok(())
}

/// Deterministic pseudo-random numbers in [0, 1).
fn noise(i: i64, salt: u64) -> f64 {
    let mut x = (i as u64).wrapping_mul(0x9E37_79B9_7F4A_7C15) ^ salt;
    x ^= x >> 31;
    x = x.wrapping_mul(0xBF58_476D_1CE4_E5B9);
    x ^= x >> 29;
    (x >> 11) as f64 / (1u64 << 53) as f64
}

fn write(
    path: &Path,
    columns: Vec<(&str, ArrayRef)>,
    maml: &str,
) -> Result<(), Box<dyn std::error::Error>> {
    let schema = Arc::new(Schema::new(
        columns
            .iter()
            .map(|(n, a)| Field::new(*n, a.data_type().clone(), a.null_count() > 0))
            .collect::<Vec<_>>(),
    ));
    let batch = RecordBatch::try_new(
        schema.clone(),
        columns.into_iter().map(|(_, a)| a).collect(),
    )?;
    let props = WriterProperties::builder()
        .set_max_row_group_row_count(Some(4_096))
        .set_key_value_metadata(Some(vec![KeyValue::new("maml".into(), maml.to_owned())]))
        .build();
    let mut writer = ArrowWriter::try_new(std::fs::File::create(path)?, schema, Some(props))?;
    writer.write(&batch)?;
    writer.close()?;
    Ok(())
}

fn write_groups(path: &Path, n: i64) -> Result<(), Box<dyn std::error::Error>> {
    let ids: Vec<i64> = (1..=n).collect();
    write(
        path,
        vec![
            ("group_id", Arc::new(Int64Array::from(ids.clone()))),
            (
                "ra",
                Arc::new(Float64Array::from_iter_values(
                    ids.iter().map(|i| noise(*i, 1) * 360.0),
                )),
            ),
            (
                "dec",
                Arc::new(Float64Array::from_iter_values(
                    ids.iter().map(|i| noise(*i, 2) * 60.0 - 30.0),
                )),
            ),
            (
                "z",
                Arc::new(Float64Array::from_iter_values(
                    ids.iter().map(|i| noise(*i, 3) * 0.8),
                )),
            ),
            (
                "n_members",
                Arc::new(Int64Array::from_iter_values(
                    ids.iter().map(|i| 2 + (noise(*i, 4) * 40.0) as i64),
                )),
            ),
            (
                "log_mass",
                Arc::new(Float64Array::from_iter_values(
                    ids.iter().map(|i| 12.0 + noise(*i, 5) * 3.0),
                )),
            ),
        ],
        "# groups\n\nGroup properties.\n\n| Column | Unit | Description |\n|---|---|---|\n\
         | group_id | | Unique group identifier |\n| ra | deg | Right ascension (J2000) |\n\
         | dec | deg | Declination (J2000) |\n| z | | Median redshift of members |\n\
         | n_members | | Number of member galaxies |\n| log_mass | log10(Msun/h) | Dynamical mass |\n",
    )
}

fn write_galaxies(path: &Path, n: i64) -> Result<(), Box<dyn std::error::Error>> {
    let ids: Vec<i64> = (1..=n).collect();
    write(
        path,
        vec![
            ("uberID", Arc::new(Int64Array::from(ids.clone()))),
            (
                "ra",
                Arc::new(Float64Array::from_iter_values(
                    ids.iter().map(|i| noise(*i, 11) * 360.0),
                )),
            ),
            (
                "dec",
                Arc::new(Float64Array::from_iter_values(
                    ids.iter().map(|i| noise(*i, 12) * 60.0 - 30.0),
                )),
            ),
            (
                "mag_r",
                Arc::new(Float64Array::from_iter_values(
                    ids.iter().map(|i| 16.0 + noise(*i, 13) * 6.0),
                )),
            ),
            (
                "z",
                Arc::new(Float64Array::from_iter(
                    ids.iter()
                        .map(|i| (noise(*i, 14) > 0.1).then(|| noise(*i, 15))),
                )),
            ),
            (
                "class",
                Arc::new(StringArray::from_iter_values(ids.iter().map(|i| {
                    ["galaxy", "star", "ambiguous"][(noise(*i, 16) * 3.0) as usize]
                }))),
            ),
            (
                "is_central",
                Arc::new(BooleanArray::from_iter(
                    ids.iter().map(|i| Some(noise(*i, 17) > 0.8)),
                )),
            ),
        ],
        "# galaxies\n\nMember galaxies.\n\n| Column | Unit | Description |\n|---|---|---|\n\
         | uberID | | Survey-wide source identifier |\n| ra | deg | Right ascension |\n\
         | dec | deg | Declination |\n| mag_r | AB mag | r-band magnitude |\n\
         | z | | Spectroscopic redshift (empty if none) |\n| class | | star / galaxy / ambiguous |\n\
         | is_central | | True for the group's central galaxy |\n",
    )
}
