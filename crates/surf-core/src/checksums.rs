//! Parsing of a version's `.checksums` file.
//!
//! The format is a few `#` comment lines followed by `<file>: <sha1>` lines.

/// One `<file>: <sha1>` line.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ChecksumEntry {
    pub file: String,
    pub sha1: String,
}

/// A parsed checksums file.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Checksums {
    /// Comment lines, with the leading `#` removed.
    pub notes: Vec<String>,
    /// Entries in file order.
    pub entries: Vec<ChecksumEntry>,
}

/// Parse a checksums file. Lines that don't match are ignored.
pub fn parse(text: &str) -> Checksums {
    let mut out = Checksums::default();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        if let Some(note) = line.strip_prefix('#') {
            out.notes.push(note.trim().to_owned());
        } else if let Some((file, sha1)) = line.rsplit_once(':') {
            let (file, sha1) = (file.trim(), sha1.trim());
            if !file.is_empty() && !sha1.is_empty() {
                out.entries.push(ChecksumEntry {
                    file: file.to_owned(),
                    sha1: sha1.to_owned(),
                });
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = "\
# This file is automatically generated upon a successful valrip directory command.
# !!DO NOT EDIT THIS FILE BY HAND!!

photometry_g09.parquet: b14543719febf085be5c0681c0f464181838ba14
photometry_wws.maml: df50a811d873a6ed9f02db19bb317f4df70137e1
not a checksum line
photometry_profound_base.md: dfc57419d310760caed8406f1e770022a2536547
";

    #[test]
    fn parses_notes_and_entries() {
        let c = parse(SAMPLE);
        assert_eq!(c.notes.len(), 2);
        assert_eq!(c.notes[1], "!!DO NOT EDIT THIS FILE BY HAND!!");
        assert_eq!(c.entries.len(), 3);
        assert_eq!(
            c.entries[0],
            ChecksumEntry {
                file: "photometry_g09.parquet".into(),
                sha1: "b14543719febf085be5c0681c0f464181838ba14".into()
            }
        );
        assert_eq!(c.entries[2].file, "photometry_profound_base.md");
    }

    #[test]
    fn handles_crlf_and_empty() {
        assert_eq!(parse("").entries.len(), 0);
        let c = parse("a.parquet: abc\r\nb.parquet: def\r\n");
        assert_eq!(c.entries[1].sha1, "def");
    }
}
